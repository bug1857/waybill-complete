(function () {
  "use strict";

  const evidence = window.WAYBILL_EVIDENCE;
  const app = document.getElementById("app");

  function element(name, className, content) {
    const node = document.createElement(name);
    if (className) node.className = className;
    if (content !== undefined) node.textContent = String(content);
    return node;
  }

  function objective(result) {
    return result.objective_value === null ? "—" : `${result.objective_value.toLocaleString()} ${result.objective_unit}`;
  }

  function statusClass(status) {
    if (status === "PROVEN_OPTIMAL_TSP") return "proven";
    if (status.includes("FEASIBLE")) return "feasible";
    if (status === "HEURISTIC_PARTIAL") return "partial";
    return "infeasible";
  }

  function badge(status) {
    return element("span", `status ${statusClass(status)}`, status.replaceAll("_", " "));
  }

  function metric(label, value, copy) {
    const card = element("section", "card metric");
    card.append(element("p", "label", label), element("p", "metric-value", value), element("p", "metric-copy", copy));
    return card;
  }

  function propertyList(items) {
    const list = element("dl");
    items.forEach(([key, value]) => {
      list.append(element("dt", "", key), element("dd", "", value ?? "—"));
    });
    return list;
  }

  function recordDetails(record) {
    const { manifest, result } = record;
    const details = element("details");
    const summary = element("summary");
    summary.append(badge(result.status), element("span", "record-name", manifest.solver_name), element("span", "record-copy", objective(result)));
    details.append(summary);
    details.append(propertyList([
      ["Input", manifest.input_name],
      ["Record hash", record.content_sha256 ?? "derived in bundle"],
      ["Matrix hash", manifest.matrix_hash],
      ["Stop reason", result.stop_reason],
      ["Lower bound", result.best_lower_bound],
      ["Reference", result.reference_value === null ? null : `${result.reference_value} ${result.objective_unit} (${result.reference_source})`],
      ["Wall time (ms)", result.wall_time_ms],
      ["Git revision", manifest.git_revision],
    ]));
    return details;
  }

  function table(records) {
    const wrap = element("div", "table-wrap");
    const tableNode = element("table");
    const header = element("thead");
    const headerRow = element("tr");
    ["Input", "Solver", "Status", "Objective", "Stop reason", "Wall time (ms)"].forEach((label) => headerRow.append(element("th", "", label)));
    header.append(headerRow);
    const body = element("tbody");
    records.forEach(({ manifest, result }) => {
      const row = element("tr");
      const statusCell = element("td");
      statusCell.append(badge(result.status));
      [manifest.input_name, manifest.solver_name].forEach((value) => row.append(element("td", "", value)));
      row.append(statusCell, element("td", "", objective(result)), element("td", "", result.stop_reason), element("td", "", result.wall_time_ms));
      body.append(row);
    });
    tableNode.append(header, body);
    wrap.append(tableNode);
    return wrap;
  }

  if (!evidence || !Array.isArray(evidence.records)) {
    app.append(element("p", "empty", "No valid embedded evidence bundle was found. Run `make evidence` before opening this page."));
    return;
  }

  const records = evidence.records;
  const exact = records.filter(({ result }) => result.status === "PROVEN_OPTIMAL_TSP");
  const fleet = records.find(({ result }) => result.problem_type === "CVRPTW");
  const uniqueExactObjectives = new Set(exact.map(({ result }) => result.objective_value));

  const masthead = element("header", "masthead");
  masthead.append(element("p", "eyebrow", "Waybill · evidence viewer"), element("span", "hash", `bundle ${evidence.content_sha256}`));
  const liveLink = element("a", "", "Live dispatch");
  liveLink.href = "live.html";
  masthead.append(liveLink);
  app.append(masthead);
  app.append(element("h1", "", "Routing evidence, without invented results."));
  app.append(element("p", "lede", "This static viewer renders the generated evidence bundle embedded beside it. It does not solve routes, call an API, or manufacture performance claims."));

  const overview = element("section", "grid");
  overview.append(
    metric("Recorded solver runs", records.length, "All rows in this view come from the bundle."),
    metric("Exact agreement", uniqueExactObjectives.size === 1 ? "yes" : "no", "Independent exact solvers on the configured validation instance."),
    metric("Fleet result", fleet ? fleet.result.status.replaceAll("_", " ") : "not recorded", "CVRPTW construction status from the same bundle."),
    metric("Bundle integrity", evidence.content_sha256 ? "verified" : "missing", "The viewer displays the payload generated by `make evidence`."),
  );
  app.append(overview);

  const highlights = element("section", "grid");
  const exactCard = element("section", "card feature");
  exactCard.append(element("p", "eyebrow", "Exact validation"), element("h2", "", "Independent solvers, one measured objective."));
  exactCard.append(element("p", "", uniqueExactObjectives.size === 1 ? `The recorded exact solvers agree on ${[...uniqueExactObjectives][0].toLocaleString()} ${exact[0].result.objective_unit}.` : "The recorded exact solvers do not agree; inspect the ledger before making a claim."));
  const fleetCard = element("section", "card feature");
  fleetCard.append(element("p", "eyebrow", "Fleet feasibility"), element("h2", "", "A complete plan is not a proof of optimality."));
  if (fleet) {
    fleetCard.append(badge(fleet.result.status), element("p", "", `Objective: ${objective(fleet.result)}. The model records this as a feasible CVRPTW heuristic result, not an optimum.`));
  } else {
    fleetCard.append(element("p", "empty", "No fleet run is present in this bundle."));
  }
  highlights.append(exactCard, fleetCard);
  app.append(highlights);

  const ledger = element("section", "wide");
  ledger.append(element("h2", "", "Run ledger"), table(records));
  app.append(ledger);

  const provenance = element("section", "card wide");
  provenance.append(element("p", "eyebrow", "Traceability"), element("h2", "", "Record-level provenance"));
  const list = element("div", "record-list");
  records.forEach((record) => list.append(recordDetails(record)));
  provenance.append(list);
  app.append(provenance);
}());
